// bench/flush.hpp —— 冲 cache（对外公开）
//
// 想让每次 rep 都像「应用第一次跑」那样从冷 cache 开始，就在 setup 里调这里的
// 函数——setup 在计时窗口【之前】执行，所以冲 cache 的耗时不会被算进去。
//
// 什么时候需要：
//   · 工作集 ≲ 目标 cache 容量，且你确实测出了差别
//   · 你想让各次 rep 互相独立，不被上一次预热
// 什么时候不需要：
//   · 工作集 ≫ cache 的流式 kernel —— 命中率本来 ≈ 0，冲不冲都是同一批内存流量
//   · 想看稳态表现（默认，也是绝大多数场景该看的）
#pragma once

#include <cstddef>

namespace bench {

// ---------------------------------------------------------------------------
// CPU 侧
// ---------------------------------------------------------------------------

// LLC（最大那一级 cache）的字节数，读 sysfs 得到。
// 读不到（非 Linux / 容器没挂 sysfs）返回 0，由调用方兜底。
std::size_t cpu_llc_bytes();

// 近似版：拿一块比 LLC 大的 buffer 整个读一遍，把工作集从各级 cache 里
// 「挤」出去。
//
// ⚠️ 这只是【大概率】，不是定理。它依赖两个前提：(a) 扫荡的 miss 会 allocate；
// (b) 替换策略不是「保留最新」那类（LIP/MRU）。现代 L2/L3 有流式检测，大块顺序、
// 不复用的访问可能被当成 streaming 用 no-allocate / evict-first 处理——那你的数据
// 可能压根没被挤出去。反过来，扫荡也可能把 cache 带进一个「流式」的状态，
// 让你【接下来的】访问也被那样对待。
//
// 本机实测（16 MB L3 / 512 KB L2，N=128 的矩阵乘，reps=200）：
//     不冲                 0.18 ms
//     flush_cpu_lines 只冲 A、B   0.18 ms   ← 精确失效自己那 128 KB，代价 ≈ 0
//     扫荡 8 MB ~ 32 MB    0.24 ~ 0.45 ms（同一份代码跨构建能差 ±40%）
// 扫荡多出来的那 0.1~0.3 ms 是【工具扰动】（在途流量 + cache 状态），不是
// 「数据被挤出 cache」的代价——后者用精确版量出来约等于 0。
//
// 判据：把「不冲」和「冲」都测出来，如果差距【远大于】「重取一遍工作集」的量级
// （本例 128 KB ≈ 6~10 µs），那多半是工具在捣乱，不是 cache 效应。
//
// bytes = 0 用整块（默认，2 倍 LLC）；想研究「冲多少才够」可以传小一点。
// 必须在写数据【之后】调：先冲再写数据等于白冲。
void flush_cpu_cache(std::size_t bytes = 0);

#if defined(__x86_64__) || defined(__i386__)

// 精确版：只冲你指定的那几块内存，不用扫 32 MB。
//
// CLFLUSH 用户态可用，作用是把该行写回并使它在【所有】cache 层失效。
// 这是它和扫荡法的本质区别：不依赖任何替换策略。
//
// 适合「地址稳定、又只想冲自己数据」的场景；地址每次都变的（比如每个 rep
// 重新 new 出来的 buffer）冲了也没意义。
//
// 注意它做不到的（这些决定了它只是「近似冷」）：
//   · 不冲 TLB。真正的冷是刚 mmap 完、页表项都没建的时候。
//   · 线程如果在 flush 之后【迁移到别的核】，flush 就白做了——L1/L2 是每核私有的。
//     想稳就绑核，见 bench/affinity.hpp。
//   · 预取器、内存控制器里的状态复位不了。
void flush_cpu_lines(void const* p, std::size_t bytes);

#endif  // x86

// ---------------------------------------------------------------------------
// GPU 侧
// ---------------------------------------------------------------------------

// 把 L2 和各 SM 的 L1/TEX 冲干净。等价于 ncu 的 --cache-control all。
// 成本：读 (2 × L2) 字节。
//
// 首次调用会 cudaMalloc 一块缓冲并一直留着，进程退出时回收。
// 故意不同步：同一个流上顺序执行，调用者后面发射的 kernel 必然在它之后。
void flush_gpu_cache();

}  // namespace bench
