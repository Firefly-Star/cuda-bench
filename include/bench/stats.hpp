// bench/stats.hpp —— 测量结果的分布（对外公开）
//
// 为什么必须报分布，而不是只报均值：
//
// 只报一个均值会把两类完全不同的东西混成同一个数：
//   · 「每次都差不多、只是整体偏慢」—— 这是【真实差异】，值得下结论
//   · 「偶尔有一次被抢占 / 降频」    —— 这是【噪声】，而均值会被它单方面拉偏
// 后者在单次只有几毫秒的区间上特别致命：一次几毫秒的抢占就能让均值偏 20%+，
// 而它其实只发生了一次。
#pragma once

#include <vector>

namespace bench {

// 一次测量的样本分布。
//
//   min    —— 最干净的那一次，最接近「没有干扰时能做到多快」。跨实现比排序时最稳。
//   median —— 典型值，不受个别离群点影响（均值会）。
//   p95    —— 差的那一侧，告诉你「抖起来能抖多狠」。
//   mean   —— 保留，只为跟历史日志对得上。
//   max    —— 最差那一次。
struct stats {
    double min = 0.0, median = 0.0, p95 = 0.0, mean = 0.0, max = 0.0;
    int    n = 0;

    // jitter = (p95 - min) / min，是【这次测量可不可信】的判据：
    //   < 5%    可信，可以拿来下结论
    //   5 ~ 20% 勉强，只看 min / median 的排序
    //   > 20%   噪声在主导 —— 这时候比较两个实现的快慢是没有意义的，先去修测量
    double jitter() const { return min > 0.0 ? (p95 - min) / min : 0.0; }
};

// 从一组样本算出上面的分布。会就地排序传进来的副本。
//
// p95 用【最近秩法】（排序后取第 ceil(0.95*n) 个），不做插值：样本只有几十个时
// 插值出来的数没有意义，最近秩法至少保证取到的是一个【真实存在的样本】。
//
// ⚠️ 代价是样本太少时 p95 会【退化成 max】，看起来像重复打印：
//     n = 10 → rank 10 = max     ← options::reps 默认 50，不会碰到
//     n = 20 → rank 19 → 第二大
//     n = 40 → rank 38
//   想让 p95 真的表示「最差那一侧」而不是「最差那一次」，reps 至少给到 20。
stats compute_stats(std::vector<double> samples);

}  // namespace bench
